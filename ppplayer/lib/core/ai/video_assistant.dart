import 'dart:async';
import 'dart:convert';

import 'package:flutter/foundation.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:http/http.dart' as http;
import 'package:youtube_explode_dart/youtube_explode_dart.dart' as yte;

import '../ultratube/ultratube_store.dart';

/// What the assistant knows about the video being watched.
class VideoContext {
  const VideoContext({
    required this.videoId,
    required this.title,
    this.channel = '',
    this.description = '',
    this.durationSeconds = 0,
    this.views = -1,
    this.uploaded = '',
    this.live = false,
    this.related = const [],
    this.recentChat = const [],
  });

  final String videoId;
  final String title;
  final String channel;
  final String description;
  final int durationSeconds;
  final int views;
  final String uploaded;
  final bool live;

  /// "Title — Channel" of YouTube's related videos (for recommendations).
  final List<String> related;

  /// Latest live chat lines ("author: text").
  final List<String> recentChat;

  String get url => 'https://www.youtube.com/watch?v=$videoId';
}

/// One exchange in the conversation.
class AskTurn {
  AskTurn(this.question, [this.answer = '']);
  final String question;
  String answer;
  bool done = false;
  String? error;
}

class AssistantException implements Exception {
  const AssistantException(this.message, {this.needsKey = false});
  final String message;
  final bool needsKey;
  @override
  String toString() => message;
}

/// Gemini (Google AI Studio) behind the "Perguntar" button: summaries,
/// key points with timestamps, related picks and free questions about the
/// current video. The user brings their own free API key; it stays in the
/// device's secure storage and requests go straight to Google.
class VideoAssistant {
  VideoAssistant._();
  static final instance = VideoAssistant._();

  static const _storage = FlutterSecureStorage();
  static const _keyName = 'gemini_api_key';
  static const defaultModel = 'gemini-flash-latest';
  static const keyPage = 'https://aistudio.google.com/apikey';

  final _http = http.Client();
  final _transcripts = <String, Future<String?>>{};

  // ------------------------------------------------------------- settings

  Future<String?> apiKey() async {
    try {
      final key = await _storage.read(key: _keyName);
      return key == null || key.trim().isEmpty ? null : key.trim();
    } catch (_) {
      return null;
    }
  }

  Future<void> setApiKey(String? key) async {
    if (key == null || key.trim().isEmpty) {
      await _storage.delete(key: _keyName);
    } else {
      await _storage.write(key: _keyName, value: key.trim());
    }
  }

  String get model => (UltratubeStore.box.get('geminiModel') as String?)?.trim().isNotEmpty == true
      ? UltratubeStore.box.get('geminiModel') as String
      : defaultModel;
  set model(String value) => UltratubeStore.box.put('geminiModel', value.trim().isEmpty ? defaultModel : value.trim());

  // ----------------------------------------------------------- transcript

  /// Captions as "[m:ss] text" lines, preferring human captions in
  /// Portuguese, then any human track, then auto-generated. Cached per video.
  Future<String?> transcript(String videoId) => _transcripts.putIfAbsent(videoId, () => _loadTranscript(videoId));

  Future<String?> _loadTranscript(String videoId) async {
    final yt = yte.YoutubeExplode();
    try {
      final manifest = await yt.videos.closedCaptions.getManifest(videoId).timeout(const Duration(seconds: 20));
      final tracks = manifest.tracks.where((t) => t.format == yte.ClosedCaptionFormat.srv3).toList();
      if (tracks.isEmpty) return null;
      int score(yte.ClosedCaptionTrackInfo t) =>
          (t.isAutoGenerated ? 0 : 10) + (t.language.code.toLowerCase().startsWith('pt') ? 5 : 0) + (t.language.code.toLowerCase().startsWith('en') ? 1 : 0);
      tracks.sort((a, b) => score(b).compareTo(score(a)));
      final track = await yt.videos.closedCaptions.get(tracks.first).timeout(const Duration(seconds: 20));
      final out = StringBuffer();
      var lastStamp = -30;
      for (final c in track.captions) {
        final text = c.text.replaceAll('\n', ' ').trim();
        if (text.isEmpty) continue;
        final s = c.offset.inSeconds;
        // A timestamp every ~15 s keeps the prompt compact but precise.
        if (s - lastStamp >= 15) {
          out.write('\n[${stamp(s)}] ');
          lastStamp = s;
        } else {
          out.write(' ');
        }
        out.write(text);
      }
      final result = out.toString().trim();
      return result.isEmpty ? null : result;
    } catch (error) {
      debugPrint('VideoAssistant: sem legendas para $videoId ($error)');
      _transcripts.remove(videoId);
      return null;
    } finally {
      yt.close();
    }
  }

  static String stamp(int seconds) {
    final h = seconds ~/ 3600, m = (seconds % 3600) ~/ 60, s = seconds % 60;
    final ss = s.toString().padLeft(2, '0');
    return h > 0 ? '$h:${m.toString().padLeft(2, '0')}:$ss' : '$m:$ss';
  }

  // ---------------------------------------------------------------- ask

  static const _system =
      'Você é o assistente de vídeos do Ultratube, como o botão "Perguntar" do YouTube. '
      'Responda sempre em português do Brasil, de forma direta e bem organizada: frases curtas, '
      'títulos com ** e listas com "- " quando ajudar. Baseie-se apenas no material do vídeo fornecido '
      '(transcrição, descrição, metadados e, em lives, o chat). Ao citar um momento do vídeo, escreva a '
      'marca de tempo entre colchetes, por exemplo [4:35] ou [1:02:10]. Se algo não estiver no vídeo, '
      'diga isso claramente em vez de inventar. Não use emojis.';

  /// Streams the answer to [question] for [video], continuing [history].
  Stream<String> ask(VideoContext video, List<AskTurn> history, String question) async* {
    final key = await apiKey();
    if (key == null) {
      throw const AssistantException('Adicione sua chave do Gemini para usar o Perguntar.', needsKey: true);
    }
    final captions = video.live ? null : await transcript(video.videoId);
    // Without captions, let Gemini watch the video itself (public videos,
    // low media resolution keeps long videos inside the context window).
    final watchVideo = captions == null && !video.live && video.durationSeconds > 0 && video.durationSeconds <= 2 * 3600;
    final context = _contextText(video, captions, watchingVideo: watchVideo);

    List<Map<String, dynamic>> contents({required bool withVideo}) => [
      for (var i = 0; i < history.length; i++) ...[
        {
          'role': 'user',
          'parts': [
            if (i == 0) ...[
              if (withVideo) {'file_data': {'file_uri': video.url}},
              {'text': context},
            ],
            {'text': history[i].question},
          ],
        },
        if (history[i].done && history[i].answer.isNotEmpty)
          {
            'role': 'model',
            'parts': [
              {'text': history[i].answer},
            ],
          },
      ],
      {
        'role': 'user',
        'parts': [
          if (history.isEmpty) ...[
            if (withVideo) {'file_data': {'file_uri': video.url}},
            {'text': context},
          ],
          {'text': question},
        ],
      },
    ];

    try {
      yield* _stream(key, contents(withVideo: watchVideo), lowMedia: watchVideo);
    } on AssistantException catch (e) {
      // Some videos can't be fetched by Gemini (age/region limits, very
      // long, private): retry with metadata only.
      if (!watchVideo || e.needsKey) rethrow;
      yield* _stream(key, contents(withVideo: false), lowMedia: false);
    }
  }

  String _contextText(VideoContext v, String? transcript, {required bool watchingVideo}) {
    final b = StringBuffer('MATERIAL DO VÍDEO\n')
      ..writeln('Título: ${v.title}')
      ..writeln('Canal: ${v.channel}');
    if (v.live) b.writeln('Tipo: transmissão AO VIVO em andamento');
    if (v.durationSeconds > 0) b.writeln('Duração: ${stamp(v.durationSeconds)}');
    if (v.views >= 0) b.writeln('${v.live ? 'Assistindo agora' : 'Visualizações'}: ${v.views}');
    if (v.uploaded.isNotEmpty) b.writeln('Publicado: ${v.uploaded}');
    final description = v.description
        .replaceAll(RegExp(r'<br\s*/?>'), '\n')
        .replaceAll(RegExp(r'<[^>]+>'), '')
        .replaceAll('&amp;', '&')
        .replaceAll('&quot;', '"')
        .replaceAll('&#39;', "'")
        .trim();
    if (description.isNotEmpty) b.writeln('\nDescrição:\n${_cap(description, 5000)}');
    if (transcript != null) {
      b.writeln('\nTranscrição (legendas, com marcas de tempo):\n${_cap(transcript, 160000)}');
    } else if (watchingVideo) {
      b.writeln('\nSem legendas: use o próprio vídeo anexado.');
    } else if (!v.live) {
      b.writeln('\nSem transcrição disponível: responda com base na descrição e nos metadados, avisando dessa limitação.');
    }
    if (v.recentChat.isNotEmpty) {
      b.writeln('\nMensagens recentes do chat ao vivo (mais antigas primeiro):');
      for (final line in v.recentChat.take(120)) {
        b.writeln(line);
      }
    }
    if (v.related.isNotEmpty) {
      b.writeln('\nVídeos relacionados disponíveis no app (use para recomendar):');
      for (final r in v.related.take(20)) {
        b.writeln('- $r');
      }
    }
    return b.toString();
  }

  static String _cap(String s, int max) => s.length <= max ? s : '${s.substring(0, max)}\n[…cortado]';

  Stream<String> _stream(String key, List<Map<String, dynamic>> contents, {required bool lowMedia}) async* {
    final uri = Uri.parse('https://generativelanguage.googleapis.com/v1beta/models/$model:streamGenerateContent?alt=sse');
    final request = http.Request('POST', uri)
      ..headers.addAll({'Content-Type': 'application/json', 'x-goog-api-key': key})
      ..body = jsonEncode({
        'system_instruction': {
          'parts': [
            {'text': _system},
          ],
        },
        'contents': contents,
        'generationConfig': {
          'temperature': 0.4,
          'maxOutputTokens': 2048,
          if (lowMedia) 'mediaResolution': 'MEDIA_RESOLUTION_LOW',
        },
      });
    final http.StreamedResponse response;
    try {
      response = await _http.send(request).timeout(const Duration(seconds: 90));
    } on TimeoutException {
      throw const AssistantException('O Gemini demorou demais para responder. Tente de novo.');
    } catch (error) {
      throw AssistantException('Sem conexão com o Gemini ($error).');
    }
    if (response.statusCode != 200) {
      final body = await response.stream.bytesToString();
      String message = body;
      try {
        message = (jsonDecode(body) as Map)['error']?['message'] as String? ?? body;
      } catch (_) {}
      throw switch (response.statusCode) {
        400 when message.toLowerCase().contains('api key') =>
          const AssistantException('Chave do Gemini inválida. Confira e salve de novo.', needsKey: true),
        401 || 403 => const AssistantException('A chave do Gemini foi recusada. Gere outra no AI Studio.', needsKey: true),
        404 => AssistantException('Modelo "$model" não encontrado. Ajuste o modelo nos ajustes do Perguntar.'),
        429 => const AssistantException('Limite de uso do Gemini atingido. Aguarde um pouco e tente de novo.'),
        _ => AssistantException('Gemini respondeu ${response.statusCode}: ${_cap(message, 200)}'),
      };
    }
    var produced = false;
    await for (final line in response.stream.transform(utf8.decoder).transform(const LineSplitter())) {
      if (!line.startsWith('data:')) continue;
      final payload = line.substring(5).trim();
      if (payload.isEmpty || payload == '[DONE]') continue;
      Map<String, dynamic> chunk;
      try {
        chunk = jsonDecode(payload) as Map<String, dynamic>;
      } catch (_) {
        continue;
      }
      final candidate = (chunk['candidates'] as List?)?.firstOrNull as Map?;
      final parts = candidate?['content']?['parts'] as List? ?? const [];
      for (final p in parts) {
        final text = (p as Map)['text'];
        // Thought summaries (thinking models) are not part of the answer.
        if (text is String && p['thought'] != true && text.isNotEmpty) {
          produced = true;
          yield text;
        }
      }
      final blocked = chunk['promptFeedback']?['blockReason'];
      if (blocked != null) throw AssistantException('O Gemini não respondeu a esta pergunta ($blocked).');
    }
    if (!produced) throw const AssistantException('O Gemini não retornou resposta. Tente reformular a pergunta.');
  }
}
